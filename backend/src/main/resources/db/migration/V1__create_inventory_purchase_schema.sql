CREATE TABLE vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(40),
    address TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_vendors_email UNIQUE (email)
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(180) NOT NULL,
    description TEXT,
    unit VARCHAR(30) NOT NULL DEFAULT 'pcs',
    current_stock NUMERIC(14,3) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_products_stock_nonnegative CHECK (current_stock >= 0)
);

CREATE TABLE purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(40) NOT NULL UNIQUE,
    vendor_id BIGINT NOT NULL REFERENCES vendors(id),
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_po_status CHECK (status IN ('OPEN', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    CONSTRAINT ck_po_total_nonnegative CHECK (total_amount >= 0)
);
CREATE INDEX idx_purchase_orders_vendor ON purchase_orders(vendor_id, order_date);

CREATE TABLE purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    ordered_quantity NUMERIC(14,3) NOT NULL,
    received_quantity NUMERIC(14,3) NOT NULL DEFAULT 0,
    unit_price NUMERIC(14,2) NOT NULL,
    line_total NUMERIC(14,2) NOT NULL,
    CONSTRAINT ck_poi_ordered_positive CHECK (ordered_quantity > 0),
    CONSTRAINT ck_poi_received_valid CHECK (received_quantity >= 0 AND received_quantity <= ordered_quantity),
    CONSTRAINT ck_poi_price_nonnegative CHECK (unit_price >= 0),
    CONSTRAINT ck_poi_line_total_nonnegative CHECK (line_total >= 0)
);
CREATE INDEX idx_poi_order ON purchase_order_items(purchase_order_id);
CREATE INDEX idx_poi_product ON purchase_order_items(product_id);

CREATE TABLE goods_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number VARCHAR(40) NOT NULL UNIQUE,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_goods_receipts_po ON goods_receipts(purchase_order_id);

CREATE TABLE goods_receipt_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id BIGINT NOT NULL REFERENCES goods_receipts(id) ON DELETE CASCADE,
    purchase_order_item_id BIGINT NOT NULL REFERENCES purchase_order_items(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    received_quantity NUMERIC(14,3) NOT NULL,
    unit_cost NUMERIC(14,2) NOT NULL,
    line_total NUMERIC(14,2) NOT NULL,
    CONSTRAINT ck_gri_quantity_positive CHECK (received_quantity > 0),
    CONSTRAINT ck_gri_unit_cost_nonnegative CHECK (unit_cost >= 0),
    CONSTRAINT ck_gri_line_total_nonnegative CHECK (line_total >= 0)
);
CREATE INDEX idx_gri_receipt ON goods_receipt_items(goods_receipt_id);
CREATE INDEX idx_gri_poi ON goods_receipt_items(purchase_order_item_id);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    movement_type VARCHAR(30) NOT NULL,
    quantity_delta NUMERIC(14,3) NOT NULL,
    reference_type VARCHAR(30) NOT NULL,
    reference_id BIGINT NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_stock_movement_nonzero CHECK (quantity_delta <> 0)
);
CREATE INDEX idx_stock_movements_product_date ON stock_movements(product_id, created_at);

CREATE TABLE vendor_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT NOT NULL REFERENCES vendors(id),
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    amount NUMERIC(14,2) NOT NULL,
    payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    method VARCHAR(30) NOT NULL DEFAULT 'BANK_TRANSFER',
    reference_number VARCHAR(100),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_vendor_payment_positive CHECK (amount > 0),
    CONSTRAINT ck_vendor_payment_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE', 'UPI', 'OTHER'))
);
CREATE INDEX idx_vendor_payments_vendor_date ON vendor_payments(vendor_id, payment_date);

